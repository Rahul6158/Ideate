export function getIdeaTheme(themeId) {
  if (!themeId) return THEME_PALETTES[0];
  const found = THEME_PALETTES.find(t => t.id === themeId);
  if (found) return found;

  // Handle custom hex colors (e.g. #FF5500 or custom-#FF5500)
  let hex = themeId.trim();
  if (hex.startsWith('custom-')) hex = hex.replace('custom-', '');
  if (!hex.startsWith('#') && /^[0-9A-Fa-f]{6}$/.test(hex)) {
    hex = '#' + hex;
  }

  if (/^#([0-9A-Fa-f]{3}|[0-9A-Fa-f]{6})$/.test(hex)) {
    return {
      id: themeId,
      name: `Custom (${hex.toUpperCase()})`,
      hex: hex,
      accentHex: hex,
      lightHex: hex + '15', // ~8% opacity
      borderHex: hex + '45', // ~27% opacity
      badge: 'bg-white/90 text-slate-800 border-slate-200',
      bannerGradient: 'from-slate-900 to-slate-800',
      headerTint: 'bg-gradient-to-r from-slate-100/70 to-transparent',
      primaryButton: 'text-white shadow-md',
      secondaryButton: 'bg-slate-100 text-slate-700 hover:bg-slate-200',
      focusRing: 'focus:ring-2 focus:ring-slate-400',
      activeTab: 'text-white',
      accentText: 'text-slate-800',
      cardBorderHover: 'hover:border-slate-300',
      tintClass: 'border-slate-500',
      isCustom: true
    };
  }

  return THEME_PALETTES[0];
}
